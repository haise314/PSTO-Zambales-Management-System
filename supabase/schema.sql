-- ============ helpers (created after profiles) ============
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  name text not null,
  role text not null default 'Staff' check (role in ('Administrator','Staff','Guest')),
  active boolean not null default true,
  must_change_password boolean not null default true,
  personnel_scope_all boolean not null default false,
  permissions jsonb not null default '{}'::jsonb,
  created_at timestamptz default now()
);

create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as
$$ select exists(select 1 from profiles where id=auth.uid() and role='Administrator' and active) $$;

create or replace function public.my_role() returns text language sql stable security definer set search_path=public as
$$ select role from profiles where id=auth.uid() and active $$;

create or replace function public.has_perm(tab text, act text) returns boolean language sql stable security definer set search_path=public as
$$ select public.is_admin() or coalesce((select (permissions->tab->>act)::boolean from profiles where id=auth.uid() and active),false) $$;

