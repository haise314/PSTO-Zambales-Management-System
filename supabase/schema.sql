-- QR codes: table is admin-only; everyone else gets the role-appropriate image through get_qr_codes()
alter table qr_codes enable row level security;
create policy qr_admin on qr_codes for all to authenticated using (is_admin()) with check (is_admin());

create or replace function public.get_qr_codes() returns table(id bigint,label text,image text,link text)
language sql stable security definer set search_path=public as $$
  select q.id,q.label,
    case when my_role()='Guest' then q.decoy_image else q.real_image end,
    case when my_role()='Guest' then q.decoy_link else q.real_link end
  from qr_codes q where my_role() is not null order by q.id $$;

create or replace function public.clear_must_change_password() returns void language sql security definer set search_path=public as
$$ update profiles set must_change_password=false where id=auth.uid() $$;

-- after a backup restore, move identity sequences past the highest restored id (admin only)
create or replace function public.reset_sequences() returns void language plpgsql security definer set search_path=public as $$
declare t text;
begin
  if not is_admin() then raise exception 'admin only'; end if;
  foreach t in array array['personnel','personnel_documents','attendance','leave_records','calendar_events','contacts','memos','trainings','email_records','documentation','funds','focal_items','qr_codes','audit_log','trash'] loop
    execute format('select setval(pg_get_serial_sequence(''public.%I'',''id''), greatest((select coalesce(max(id),0) from public.%I),1))', t, t);
  end loop;
end $$;

revoke execute on function public.get_qr_codes(), public.clear_must_change_password(), public.reset_sequences() from public, anon;
grant execute on function public.get_qr_codes(), public.clear_must_change_password(), public.reset_sequences() to authenticated;

