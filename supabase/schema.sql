create or replace function public.can_manage_person(pid bigint) returns boolean language sql stable security definer set search_path=public as
$$ select public.is_admin() or (public.my_role()='Staff' and (
     exists(select 1 from profiles where id=auth.uid() and personnel_scope_all)
     or exists(select 1 from personnel where id=pid and user_id=auth.uid()))) $$;

