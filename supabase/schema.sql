-- ============ triggers ============
create or replace function public.personnel_set_name() returns trigger language plpgsql as $$
begin
  new.name := coalesce(nullif(trim(concat_ws(' ',nullif(new.first_name,''),nullif(new.middle_name,''),nullif(new.last_name,''),nullif(new.suffix,''))),''), new.name, '');
  return new;
end $$;
create trigger trg_personnel_name before insert or update on personnel for each row execute function personnel_set_name();

-- when a personnel name changes, keep name-based references consistent
create or replace function public.personnel_rename_cascade() returns trigger language plpgsql security definer set search_path=public as $$
begin
  if old.name is distinct from new.name and coalesce(old.name,'')<>'' then
    update attendance set employee=new.name where employee=old.name;
    update leave_records set employee=new.name where employee=old.name;
    update email_records set assigned_to=new.name where assigned_to=old.name;
    update focal_items set focal=new.name where focal=old.name;
    update focal_items set alternate=new.name where alternate=old.name;
    update calendar_events set title=new.name||substr(title,length(old.name)+1) where left(title,length(old.name)+3)=old.name||' — ';
  end if;
  return new;
end $$;
create trigger trg_personnel_rename after update on personnel for each row execute function personnel_rename_cascade();

-- approved leave automatically appears on the calendar
create or replace function public.sync_leave_calendar() returns trigger language plpgsql security definer set search_path=public as $$
declare pid bigint; lbl text; ed date;
begin
  if new.status<>'Approved' or new.date_from is null then
    delete from calendar_events where linked_leave_id=new.id; return new;
  end if;
  select id into pid from personnel where name=new.employee limit 1;
  lbl := case when new.type='Others' and coalesce(new.other_type,'')<>'' then new.other_type else new.type end;
  ed := case when new.date_to is not null and new.date_to>=new.date_from then new.date_to else new.date_from end;
  insert into calendar_events(title,category,start_date,end_date,person_ids,remarks,linked_leave_id,added_by,added_by_name)
  values(coalesce(new.employee,'Personnel')||' — '||coalesce(lbl,'Leave'),'Leave',new.date_from,ed,
         case when pid is null then '{}'::bigint[] else array[pid] end,
         'Auto-synced from approved Leave record. '||coalesce(new.remarks,''),new.id,new.added_by,new.added_by_name)
  on conflict (linked_leave_id) do update set title=excluded.title,start_date=excluded.start_date,
    end_date=excluded.end_date,person_ids=excluded.person_ids,remarks=excluded.remarks;
  return new;
end $$;
create trigger trg_leave_calendar after insert or update on leave_records for each row execute function sync_leave_calendar();

-- ============ row level security ============
alter table profiles enable row level security;
create policy profiles_select on profiles for select to authenticated using (id=auth.uid() or is_admin());
create policy profiles_admin_write on profiles for all to authenticated using (is_admin()) with check (is_admin());

-- standard modules: permission matrix from profiles.permissions; edit/delete limited to the owner (admins: all)
do $$ declare r record; begin
  for r in select * from (values ('attendance','attendance'),('leave_records','leave'),('contacts','contacts'),('memos','memos'),
    ('trainings','trainings'),('email_records','email'),('documentation','documentation'),('calendar_events','calendar')) v(t,tab) loop
    execute format('alter table public.%I enable row level security', r.t);
    execute format('create policy "%1$s_select" on public.%1$I for select to authenticated using (public.has_perm(%2$L,''view''))', r.t, r.tab);
    execute format('create policy "%1$s_insert" on public.%1$I for insert to authenticated with check (public.has_perm(%2$L,''add'') and (added_by=auth.uid() or public.is_admin()))', r.t, r.tab);
    execute format('create policy "%1$s_update" on public.%1$I for update to authenticated using (public.has_perm(%2$L,''edit'') and (added_by=auth.uid() or public.is_admin()))', r.t, r.tab);
    execute format('create policy "%1$s_delete" on public.%1$I for delete to authenticated using (public.has_perm(%2$L,''delete'') and (added_by=auth.uid() or public.is_admin()))', r.t, r.tab);
  end loop;
end $$;

-- calendar: Staff may also edit/delete activities they are tagged on
create policy calendar_tagged_update on calendar_events for update to authenticated
  using (my_role()='Staff' and has_perm('calendar','edit') and exists(select 1 from personnel p where p.user_id=auth.uid() and p.id=any(person_ids)));
create policy calendar_tagged_delete on calendar_events for delete to authenticated
  using (my_role()='Staff' and has_perm('calendar','delete') and exists(select 1 from personnel p where p.user_id=auth.uid() and p.id=any(person_ids)));

-- personnel
alter table personnel enable row level security;
create policy personnel_select on personnel for select to authenticated using (
  has_perm('personnel','view') and (is_admin() or (status<>'Inactive' and
    (user_id is null or exists(select 1 from profiles pr where pr.id=personnel.user_id and pr.active)))));
create policy personnel_insert on personnel for insert to authenticated with check (is_admin());
create policy personnel_delete on personnel for delete to authenticated using (is_admin());
create policy personnel_update on personnel for update to authenticated using (
  is_admin() or (has_perm('personnel','edit') and (user_id=auth.uid() or exists(select 1 from profiles where id=auth.uid() and personnel_scope_all))));

alter table personnel_documents enable row level security;
create policy pdoc_select on personnel_documents for select to authenticated using (has_perm('personnel','view'));
create policy pdoc_write on personnel_documents for all to authenticated using (can_manage_person(personnel_id)) with check (can_manage_person(personnel_id));

alter table personnel_doc_links enable row level security;
create policy plink_select on personnel_doc_links for select to authenticated using (
  is_admin() or exists(select 1 from personnel_documents d join personnel p on p.id=d.personnel_id where d.id=doc_id and p.user_id=auth.uid()));
create policy plink_write on personnel_doc_links for all to authenticated
  using (exists(select 1 from personnel_documents d where d.id=doc_id and can_manage_person(d.personnel_id)))
  with check (exists(select 1 from personnel_documents d where d.id=doc_id and can_manage_person(d.personnel_id)));

